import { useState } from "react";
import { Link, useParams } from "react-router-dom";
import { useTranslation } from "react-i18next";
import { useCurrent } from "../../lib/auth/CurrentUserContext";
import { statusLabel } from "../../lib/locations";
import { date, dateTime } from "../../i18n";
import { attachmentOf, targetPath } from "../../data/attachments";
import { NoteDialog } from "../shared/NoteDialog";
import { PRIORITY_ORDER, priorityBadgeClass } from "../../lib/workItems";
import { describeUpdate, isChange } from "../../lib/recordHistory";
import {
  addTicketComment,
  assignTicket,
  setTicketPriority,
  setTicketStatus,
  useTicket,
  useTicketUpdates,
} from "../../data/tickets";
import { useTicketStatuses } from "../../data/lookups";
import { useUsers } from "../../data/users";

// Tickets — Ticket Detail (see TicketDetailPage.spec.md).
// Status/priority edits are unrestricted; only assignment is gated. A ticket
// with a source incident shows no trace of it without view_incidents. The
// history is the ticket's own Ticket Updates, shown as a timeline with a
// comment box at its end.

export function TicketDetailPage() {
  const { id: ticketId } = useParams();
  const current = useCurrent();
  const { t } = useTranslation("tickets");
  const [showNoteDialog, setShowNoteDialog] = useState(false);
  const [comment, setComment] = useState("");

  const { ticket } = useTicket(ticketId);
  const { data: users } = useUsers();
  const { data: updates } = useTicketUpdates(ticketId);
  // The status list is the marina's own, so a marina that added "Waiting on
  // parts" gets it here without a code change. The ticket's current status is
  // always included even if it was since retired, or a ticket would silently
  // change status by being looked at.
  const { statuses } = useTicketStatuses();

  if (!ticket) {
    return (
      <div className="placeholder">
        <div className="big">{t("detail.loading")}</div>
      </div>
    );
  }

  const target = attachmentOf(ticket);
  const actorId = current.user?.id ?? null;
  const when = (ts: string) => dateTime(ts, { month: "short", day: "numeric", hour: "numeric", minute: "2-digit" });

  // A change that changes nothing is not written (spec § Actions).
  const setStatus = (statusId: string) => {
    const status = statuses.find((s) => s.id === statusId);
    if (status && isChange(ticket.status_id, statusId)) void setTicketStatus(ticket, status, actorId);
  };
  const setPriority = (priority: string) => {
    if (!isChange(ticket.priority, priority)) return;
    void setTicketPriority(ticket, priority, { from: statusLabel(ticket.priority), to: statusLabel(priority) }, actorId);
  };
  const assign = (userId: string) => {
    if (!userId || !isChange(ticket.assigned_to_id, userId)) return;
    const assignee = users.find((u) => u.id === userId);
    void assignTicket(ticket, { id: userId, name: assignee?.name ?? "" }, actorId);
  };
  const addComment = async () => {
    if (!comment.trim()) return;
    await addTicketComment(ticket, comment.trim(), actorId);
    setComment("");
  };

  // Tickets from before Updates existed have no `created` row; the ticket
  // itself still says who made it, so the timeline never reads as empty.
  const hasCreated = updates.some((u) => u.kind === "created");

  return (
    <div>
      <div className="page-head">
        <div>
          <h1 className="page-title">{ticket.title}</h1>
          <div className="page-sub">
            {t("detail.createdBy", { name: ticket.creator_name ?? "—", when: when(ticket.created_at) })}
            {ticket.auto_generated === 1 && ` · ${t("detail.autoGenerated")}`}
          </div>
        </div>
        <button type="button" className="btn btn-sm" onClick={() => setShowNoteDialog(true)} disabled={!target}>
          {t("detail.addNote")}
        </button>
      </div>

      <div className="grid-2">
        <div>
          <div className="field">
            <span className="field-label">{t("detail.priority")}</span>
            <select
              className="select select-inline"
              aria-label={t("detail.priority")}
              value={ticket.priority}
              onChange={(e) => setPriority(e.target.value)}
            >
              {PRIORITY_ORDER.map((p) => (
                <option key={p} value={p}>
                  {statusLabel(p)}
                </option>
              ))}
            </select>{" "}
            <span className={priorityBadgeClass(ticket.priority)}>{statusLabel(ticket.priority)}</span>
          </div>

          <div className="field">
            <span className="field-label">{t("detail.status")}</span>
            <select
              className="select select-inline"
              aria-label={t("detail.status")}
              value={ticket.status_id}
              onChange={(e) => setStatus(e.target.value)}
            >
              {statuses.some((s) => s.id === ticket.status_id) || (
                <option value={ticket.status_id}>{ticket.status_name}</option>
              )}
              {statuses.map((s) => (
                <option key={s.id} value={s.id}>
                  {s.name}
                </option>
              ))}
            </select>
            {ticket.resolved_at && (
              <span className="muted small"> {t("detail.resolvedOn", { date: date(ticket.resolved_at) })}</span>
            )}
          </div>

          <div className="field">
            <span className="field-label">{t("detail.assignedTo")}</span>
            <div className="field-value row">
              <span>{ticket.assignee_name ?? <span className="muted">{t("detail.unassigned")}</span>}</span>
              {!ticket.assigned_to_id && current.can("assign_ticket_to_self") && (
                <button type="button" className="btn btn-sm" onClick={() => current.user && assign(current.user.id)}>
                  {t("detail.take")}
                </button>
              )}
              {current.can("assign_ticket_to_others") && (
                <select
                  className="select select-inline"
                  aria-label={t("detail.assignedTo")}
                  value=""
                  onChange={(e) => assign(e.target.value)}
                >
                  <option value="">{t("detail.assignPlaceholder")}</option>
                  {users.map((u) => (
                    <option key={u.id} value={u.id}>
                      {u.name}
                    </option>
                  ))}
                </select>
              )}
            </div>
          </div>

          {target && (
            <div className="field">
              <span className="field-label">{t("detail.attachedTo")}</span>
              <div className="field-value">
                <Link to={targetPath(target)}>{target.label}</Link>
              </div>
            </div>
          )}

          {ticket.source_incident_id && current.can("view_incidents") && (
            <div className="field">
              <span className="field-label">{t("detail.sourceIncident")}</span>
              <div className="field-value">
                <Link to={`/incidents/${ticket.source_incident_id}`}>
                  {/* The incident itself may be outside this device's sync
                      window even when the ticket is not, so its title can be
                      absent while the link still works online. */}
                  {ticket.source_incident_title ?? t("detail.incidentFallback")}
                </Link>
              </div>
            </div>
          )}

          {ticket.description ? (
            <div className="card">
              {/* Markdown source shown as plain text until a renderer lands. */}
              <div className="small" style={{ whiteSpace: "pre-wrap" }}>
                {ticket.description}
              </div>
            </div>
          ) : (
            <p className="muted small">{t("detail.noDescription")}</p>
          )}
        </div>

        <div>
          <div className="section-title">{t("detail.history")}</div>
          <ol className="stack" data-testid="ticket-timeline" style={{ gap: 8, listStyle: "none", padding: 0, margin: 0 }}>
            {!hasCreated && (
              <li className="card" data-kind="created">
                <div className="small">{t("timeline.created", { name: ticket.creator_name ?? "—" })}</div>
                <div className="card-meta">{when(ticket.created_at)}</div>
              </li>
            )}
            {updates.map((u) => {
              const d = describeUpdate(u);
              return (
                <li key={u.id} className="card" data-kind={u.kind}>
                  <div className="small" style={{ whiteSpace: "pre-wrap" }}>
                    {t(d.key as "timeline.status", d.values as { from: string; to: string })}
                  </div>
                  <div className="card-meta">{t("timeline.by", { name: u.author_name ?? "—", when: when(u.created_at) })}</div>
                </li>
              );
            })}
          </ol>

          <div style={{ marginTop: 12 }}>
            <textarea
              className="textarea"
              rows={3}
              value={comment}
              onChange={(e) => setComment(e.target.value)}
              placeholder={t("detail.commentPlaceholder")}
              aria-label={t("detail.commentPlaceholder")}
            />
            <div className="row" style={{ marginTop: 8 }}>
              <button
                type="button"
                className="btn btn-primary btn-sm"
                disabled={!comment.trim()}
                onClick={() => void addComment()}
              >
                {t("detail.addComment")}
              </button>
            </div>
          </div>
        </div>
      </div>

      {showNoteDialog && target && <NoteDialog target={target} onClose={() => setShowNoteDialog(false)} />}
    </div>
  );
}
