import { useQuery } from "@powersync/react";
import { db, stamp } from "../lib/db";
import { dataT } from "../i18n";
import { insert, transact, update, type Executor } from "./sql";
import { recordActivity } from "./activity";
import {
  attachmentColumns,
  attachmentJoins,
  attachmentSelect,
  type AttachedRow,
  type AttachmentTarget,
} from "./attachments";

// Tickets — the marina's work queue.
//
// Deliberately ungated: every role sees the queue and can raise a ticket. Only
// taking and assigning are permission-checked, and only in the UI — a ticket is
// Tier 0 in RLS, so the database will accept an assignment from anyone. That is
// the documented split, not an oversight; see docs/permissions.md.
//
// Every write to `tickets` is in this file, and each writes its Ticket Update
// in the same transaction (TicketDetailPage.spec.md § Ticket Updates, ADR
// 0008). src/lib/ownedWrites.test.ts holds every other module to that.

export interface TicketRow extends AttachedRow {
  id: string;
  title: string;
  description: string | null;
  priority: string;
  status_id: string;
  auto_generated: number;
  created_at: string;
  resolved_at: string | null;
  created_by_id: string | null;
  assigned_to_id: string | null;
  source_incident_id: string | null;
  source_checklist_item_id: string | null;
  status_name: string;
  status_is_terminal: number;
  assignee_name: string | null;
  creator_name: string | null;
  source_incident_title: string | null;
}

const TICKET_SELECT = `
  SELECT t.*,
         s.name AS status_name,
         s.is_terminal AS status_is_terminal,
         au.name AS assignee_name,
         cu.name AS creator_name,
         si.title AS source_incident_title,
         ${attachmentSelect("t")}
    FROM tickets t
    JOIN ticket_statuses s ON s.id = t.status_id
    LEFT JOIN users au ON au.id = t.assigned_to_id
    LEFT JOIN users cu ON cu.id = t.created_by_id
    LEFT JOIN incidents si ON si.id = t.source_incident_id
    ${attachmentJoins("t")}`;

/**
 * The queue, urgent first and newest within a priority.
 *
 * Priority is an enum whose declaration order is low→urgent, and SQLite has no
 * knowledge of that ordering — so it is spelled out here rather than sorted in
 * JavaScript after the fact, which would have to re-sort on every render.
 */
export function useTickets() {
  return useQuery<TicketRow>(
    `${TICKET_SELECT}
      ORDER BY CASE t.priority
                 WHEN 'urgent' THEN 0 WHEN 'high' THEN 1
                 WHEN 'medium' THEN 2 WHEN 'low' THEN 3 ELSE 4 END,
               t.created_at DESC`,
  );
}

export function useTicket(ticketId: string | undefined) {
  const { data, isLoading } = useQuery<TicketRow>(
    `${TICKET_SELECT} WHERE t.id = ?`,
    [ticketId ?? ""],
  );
  return { ticket: data[0] ?? null, isLoading };
}

/** Open tickets attached to one target — a location's or asset's own queue. */
export function useTicketsForTarget(
  column: "location_id" | "checkpoint_id" | "boat_id" | "vehicle_id" | "contact_id" | "asset_id",
  targetId: string | undefined,
) {
  return useQuery<TicketRow>(
    `${TICKET_SELECT} WHERE t.${column} = ? ORDER BY t.created_at DESC`,
    [targetId ?? ""],
  );
}

export interface TicketUpdateRow {
  id: string;
  ticket_id: string;
  kind: string;
  from_value: string | null;
  to_value: string | null;
  body: string | null;
  created_at: string;
  author_id: string | null;
  author_name: string | null;
}

/** A Ticket's history, oldest first. */
export function useTicketUpdates(ticketId: string | undefined) {
  return useQuery<TicketUpdateRow>(
    `SELECT u.*, a.name AS author_name
       FROM ticket_updates u
       LEFT JOIN users a ON a.id = u.author_id
      WHERE u.ticket_id = ?
      ORDER BY u.created_at, u.id`,
    [ticketId ?? ""],
  );
}

/** Where a ticket came from, for its `created` Update: a catalog key under tickets:origin. */
export type TicketOrigin = "checklist" | "maintenance" | "audit" | "haulOut";

async function writeUpdate(
  tx: Executor,
  ticketId: string,
  row: { kind: string; from?: string | null; to?: string | null; body?: string | null; at?: string },
  actorId: string | null,
): Promise<void> {
  await insert(tx, "ticket_updates", {
    ticket_id: ticketId,
    kind: row.kind,
    from_value: row.from ?? null,
    to_value: row.to ?? null,
    body: row.body ?? null,
    created_at: row.at ?? stamp(),
    author_id: actorId,
  });
}

/**
 * Create a ticket inside a caller's transaction: a checklist submit, a
 * maintenance rule, a haul-out. Writes the `created` Update beside it and,
 * when `activityTarget` is given, the Activity Log entry; callers that write
 * their own log line pass nothing.
 */
export async function insertTicket(
  tx: Executor,
  row: {
    id?: string;
    title: string;
    description?: string | null;
    priority: string;
    statusId: string;
    autoGenerated?: boolean;
    createdAt?: string;
    sourceIncidentId?: string | null;
    sourceChecklistItemId?: string | null;
    sourceFindingId?: string | null;
    proposalId?: string | null;
    target: AttachmentTarget | null;
  },
  actorId: string | null,
  origin: TicketOrigin | null,
): Promise<string> {
  const at = row.createdAt ?? stamp();
  const ticketId = await insert(tx, "tickets", {
    id: row.id,
    title: row.title,
    description: row.description || null,
    priority: row.priority,
    status_id: row.statusId,
    auto_generated: row.autoGenerated ? 1 : 0,
    created_at: at,
    created_by_id: actorId,
    source_incident_id: row.sourceIncidentId ?? null,
    source_checklist_item_id: row.sourceChecklistItemId ?? null,
    source_finding_id: row.sourceFindingId ?? null,
    proposal_id: row.proposalId ?? null,
    ...attachmentColumns(row.target),
  });
  await writeUpdate(
    tx,
    ticketId,
    { kind: "created", to: origin ? dataT(`origin.${origin}`, { ns: "tickets" }) : null, at },
    actorId,
  );
  return ticketId;
}

export interface NewTicket {
  title: string;
  description?: string;
  priority: string;
  target: AttachmentTarget;
  statusId: string;
  sourceIncidentId?: string | null;
  sourceChecklistItemId?: string | null;
  /** Raised from an audit Finding. */
  sourceFindingId?: string | null;
  /** Raised against a proposed new Location: attached to the proposed parent
   *  until finalize re-targets it (docs/audits.md § What becomes a Proposal). */
  proposalId?: string | null;
  autoGenerated?: boolean;
}

export async function createTicket(
  input: NewTicket,
  actorId: string | null,
  origin: TicketOrigin | null = null,
): Promise<string> {
  return transact(async (tx) => {
    const ticketId = await insertTicket(tx, { ...input, target: input.target }, actorId, origin);
    await recordActivity(tx, {
      eventType: "ticket.created",
      summary: dataT("activity.created", { ns: "tickets", title: input.title, target: input.target.label }),
      subjectType: "tickets",
      subjectId: ticketId,
      actorId,
    });
    return ticketId;
  });
}

export async function assignTicket(
  ticket: { id: string; title: string; assigned_to_id?: string | null; assignee_name?: string | null },
  assignee: { id: string; name: string },
  actorId: string | null,
): Promise<void> {
  if (ticket.assigned_to_id === assignee.id) return;
  await transact(async (tx) => {
    await update(tx, "tickets", ticket.id, { assigned_to_id: assignee.id });
    await writeUpdate(tx, ticket.id, { kind: "assignee", from: ticket.assignee_name ?? null, to: assignee.name }, actorId);
    await recordActivity(tx, {
      eventType: "ticket.assigned",
      summary: dataT("activity.assigned", { ns: "tickets", title: ticket.title, name: assignee.name }),
      subjectType: "tickets",
      subjectId: ticket.id,
      actorId,
    });
  });
}

export async function setTicketStatus(
  ticket: { id: string; title: string; status_id?: string; status_name?: string | null },
  status: { id: string; name: string; is_terminal: number },
  actorId: string | null,
): Promise<void> {
  if (ticket.status_id === status.id) return;
  await transact(async (tx) => {
    await update(tx, "tickets", ticket.id, {
      status_id: status.id,
      // resolved_at tracks the terminal status, and is cleared if the ticket
      // reopens — the maintenance-rule baseline reads it, so a stale value
      // suppresses the next rule firing rather than merely looking wrong.
      resolved_at: status.is_terminal === 1 ? stamp() : null,
    });
    await writeUpdate(tx, ticket.id, { kind: "status", from: ticket.status_name ?? null, to: status.name }, actorId);
    await recordActivity(tx, {
      eventType: "ticket.status_changed",
      summary: dataT("activity.status", { ns: "tickets", title: ticket.title, status: status.name }),
      subjectType: "tickets",
      subjectId: ticket.id,
      actorId,
    });
  });
}

export async function setTicketPriority(
  ticket: { id: string; title: string; priority?: string },
  priority: string,
  /** The new and current priorities as shown, the names the Update keeps. */
  labels: { from: string; to: string },
  actorId: string | null,
): Promise<void> {
  if (ticket.priority === priority) return;
  await transact(async (tx) => {
    await update(tx, "tickets", ticket.id, { priority });
    await writeUpdate(tx, ticket.id, { kind: "priority", from: labels.from, to: labels.to }, actorId);
    await recordActivity(tx, {
      eventType: "ticket.priority_changed",
      summary: dataT("activity.priority", { ns: "tickets", title: ticket.title, priority: labels.to }),
      subjectType: "tickets",
      subjectId: ticket.id,
      actorId,
    });
  });
}

/** A comment: a `comment` Update. Append-only; ungated, like changing status. */
export async function addTicketComment(
  ticket: { id: string; title: string },
  body: string,
  actorId: string | null,
): Promise<void> {
  await transact(async (tx) => {
    await writeUpdate(tx, ticket.id, { kind: "comment", body }, actorId);
    await recordActivity(tx, {
      eventType: "ticket.commented",
      summary: dataT("activity.commented", { ns: "tickets", title: ticket.title }),
      subjectType: "tickets",
      subjectId: ticket.id,
      actorId,
    });
  });
}

/** Open auto-generated tickets for an asset, for the maintenance-rule check. */
export function ticketsForAsset(assetId: string): Promise<TicketRow[]> {
  return db.getAll<TicketRow>(
    `${TICKET_SELECT} WHERE t.asset_id = ? AND t.auto_generated = 1`,
    [assetId],
  );
}
